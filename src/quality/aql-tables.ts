const DECIMAL_REGEX = /^(\d+)(?:\.(\d+))?$/;

/**
 * Normalizes a decimal STRING (for example '1.000', '1', '1.0', '0.10', '00.1') to the preferred
 * AQL key it denotes, or null when it is not one of the standard's 26 preferred values. Pure string
 * arithmetic: leading integer zeros and trailing fraction zeros are stripped and the result is
 * compared against every preferred value normalized the same way. Never uses Number.
 */
export function canonicalAql(value: string): PreferredAql | null {
  const normalized = normalizeDecimal(value);
  if (normalized === null) return null;
  for (const aql of PREFERRED_AQLS) {
    if (normalizeDecimal(aql) === normalized) return aql;
  }
  return null;
}

function normalizeDecimal(value: string): string | null {
  if (typeof value !== 'string') return null;
  const m = DECIMAL_REGEX.exec(value.trim());
  if (!m) return null;
  const int = m[1]!.replace(/^0+(?=\d)/, '');
  const frac = (m[2] ?? '').replace(/0+$/, '');
  return frac.length > 0 ? `${int}.${frac}` : int;
}

export function isInspectionLevel(value: unknown): value is InspectionLevel {
  return typeof value === 'string' && (INSPECTION_LEVELS as readonly string[]).includes(value);
}

export function isCodeLetter(value: unknown): value is CodeLetter {
  return typeof value === 'string' && (CODE_LETTERS as readonly string[]).includes(value);
}

/**
 * Table I lookup. Returns null when the lot size is below the first band (2), which the caller
 * treats as "inspect the whole lot" (Annex requirement 4).
 */
export function codeLetterFor(lotSize: number, level: InspectionLevel): CodeLetter | null {
  if (!Number.isSafeInteger(lotSize) || lotSize < LOT_SIZE_BANDS[0]!.min) return null;
  const letters = CODE_LETTER_TABLE[level];
  for (let i = 0; i < LOT_SIZE_BANDS.length; i += 1) {
    const band = LOT_SIZE_BANDS[i]!;
    if (lotSize >= band.min && (band.max === null || lotSize <= band.max)) return letters[i]!;
  }
  return null;
}

export interface SingleSamplingPlan {
  code_letter: CodeLetter;
  /** The letter whose row supplied the plan after arrow resolution (equals code_letter when no arrow). */
  resolved_letter: CodeLetter;
  sample_size: number;
  ac: number;
  re: number;
}

/**
 * Tables II-A / II-B / II-C lookup with arrow resolution: an arrow cell is followed down (or up)
 * the same AQL column to the first plan cell, and that row's sample size is used. Returns null
 * only if a column were entirely arrows, which the transcription guarantees never happens.
 */
export function singleSamplingPlan(
  letter: CodeLetter,
  aql: PreferredAql,
  severity: Severity,
): SingleSamplingPlan | null {
  const column = PREFERRED_AQLS.indexOf(aql);
  if (column < 0) return null;
  const table = TABLES_BY_SEVERITY[severity];
  const sizes = severity === 'reduced' ? REDUCED_SAMPLE_SIZES : SAMPLE_SIZES;
  let row = CODE_LETTERS.indexOf(letter);
  let cell = table[letter]![column]!;
  let guard = 0;
  while (typeof cell === 'string') {
    row += cell === 'down' ? 1 : -1;
    guard += 1;
    if (row < 0 || row >= CODE_LETTERS.length || guard > CODE_LETTERS.length) return null;
    cell = table[CODE_LETTERS[row]!]![column]!;
  }
  const resolved = CODE_LETTERS[row]!;
  return {
    code_letter: letter,
    resolved_letter: resolved,
    sample_size: sizes[resolved],
    ac: cell.ac,
    re: cell.re,
  };
}

/** The preferred AQL one step tighter (smaller) than `aql`, or null at the first column. */
export function tighterAql(aql: PreferredAql): PreferredAql | null {
  const column = PREFERRED_AQLS.indexOf(aql);
  return column > 0 ? PREFERRED_AQLS[column - 1]! : null;
}
