/**
 * Story 8.2 (FR-Q-03): IS 2500 (Part 1):2000 / ISO 2859-1:1999 single-sampling tables as DATA.
 *
 * Table I (sample-size code letters), Table II-A (single sampling, normal inspection), Table II-B
 * (tightened) and Table II-C (reduced) are transcribed below as literal cells; no plan is computed by
 * formula (Annex requirement 1). Arrow cells are kept as 'down' / 'up' exactly as printed and are
 * resolved by singleSamplingPlan() per the standard's rule: follow the arrow to the first plan cell
 * in the same column and use THAT row's sample size.
 *
 * Transcription notes (verified against the story's pinned anchor cells, Dev Notes Table 3):
 * - Tables II-A and II-C carry eleven plan diagonals (Ac 0, 1, 2, 3, 5, 7, 10, 14, 21, 30, 44 on
 *   normal; the gapped Ac/Re pairs on reduced); Table II-B carries ten (0, 1, 2, 3, 5, 8, 12, 18,
 *   27, 41). The Ac = 0 diagonal passes through G at AQL 1.0 on normal and reduced, and through H at
 *   AQL 1.0 on tightened.
 * - The standard prints a supplementary code letter S (n = 3150) at the bottom-left of Table II-B
 *   for AQL 0.010 and 0.015 at letter R. This module keeps the 16-letter vocabulary the story
 *   pins (A to R, no I or O) and records those corner cells - R at AQL 0.010 and 0.015 on II-A and
 *   II-C, and R at AQL 0.010, 0.015 and 0.025 on II-B - as Ac 0 / Re 1 at n = 2000, the tightest
 *   plan the 16-letter tables offer; a down arrow with no plan beneath it would otherwise be
 *   unresolvable.
 * - Sample sizes: A 2, B 3, C 5, D 8, E 13, F 20, G 32, H 50, J 80, K 125, L 200, M 315, N 500,
 *   P 800, Q 1250, R 2000 (normal and tightened); reduced 2, 2, 2, 3, 5, 8, 13, 20, 32, 50, 80,
 *   125, 200, 315, 500, 800.
 *
 * Every value is exact: AQLs are decimal STRINGS (never Number), integers are only ever the table's
 * own integers (sample size, Ac, Re). Nothing in this module reaches the database.
 */

